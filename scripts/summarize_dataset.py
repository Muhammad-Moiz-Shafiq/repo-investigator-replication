"""Generates a point-in-time snapshot of what's actually in the database --
row counts and date coverage per repo, per table -- and saves it as a new,
timestamped file under docs/dataset_snapshots/ (never overwritten, same
convention as evaluation_results/), instead of only living in
docs/data_engineering_log.md's prose.

Usage: uv run --group db python scripts/summarize_dataset.py
"""

import json
import os
from datetime import UTC, datetime
from pathlib import Path

from repo_investigator.db.connection import get_psycopg_connection

# (table, date_column or None if the table has no per-row date to range over)
TABLES = [
    ("commits", "committed_at"),
    ("pull_requests", "created_at"),
    ("pr_reviews", None),  # has repo_id directly
    ("issues", "created_at"),
    ("ci_runs", "started_at"),
]


def main():
    conn = get_psycopg_connection(os.environ["DATABASE_URL"])
    snapshot = {"generated_at": datetime.now(UTC).isoformat(), "repos": {}}

    with conn.cursor() as cur:
        cur.execute("SELECT id, owner, name FROM repos ORDER BY owner, name")
        repos = cur.fetchall()

        for repo_id, owner, name in repos:
            repo_key = f"{owner}/{name}"
            snapshot["repos"][repo_key] = {}
            for table, date_col in TABLES:
                if date_col:
                    cur.execute(
                        f"SELECT count(*), min({date_col}), max({date_col}) "  # noqa: S608 -- fixed allowlist above, not user input
                        f"FROM {table} WHERE repo_id = %s",
                        (repo_id,),
                    )
                    count, min_date, max_date = cur.fetchone()
                    snapshot["repos"][repo_key][table] = {
                        "row_count": count,
                        "date_from": min_date.isoformat() if min_date else None,
                        "date_to": max_date.isoformat() if max_date else None,
                    }
                else:
                    # pr_reviews has repo_id directly -- no join needed.
                    cur.execute(
                        f"SELECT count(*) FROM {table} WHERE repo_id = %s",  # noqa: S608 -- fixed allowlist above
                        (repo_id,),
                    )
                    (count,) = cur.fetchone()
                    snapshot["repos"][repo_key][table] = {"row_count": count}

            # commit_files has no repo_id or date column of its own -- joins
            # through commits.sha to scope it per repo.
            cur.execute(
                "SELECT count(*) FROM commit_files cf JOIN commits c ON cf.commit_sha = c.sha "
                "WHERE c.repo_id = %s",
                (repo_id,),
            )
            (commit_files_count,) = cur.fetchone()
            snapshot["repos"][repo_key]["commit_files"] = {"row_count": commit_files_count}

    conn.close()

    # Timestamped and never overwritten, same convention as evaluation_results/
    # -- each run is a permanent snapshot, so dataset state at any past point
    # (e.g. before/after an ingestion change) stays reconstructable.
    out_dir = Path(__file__).parent.parent / "docs" / "dataset_snapshots"
    out_dir.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")

    json_path = out_dir / f"dataset_summary_{timestamp}.json"
    json_path.write_text(json.dumps(snapshot, indent=2))

    md_lines = [
        "# Dataset summary (auto-generated by scripts/summarize_dataset.py -- do not hand-edit)",
        "",
        f"Generated: {snapshot['generated_at']}",
        "",
    ]
    for repo_key, tables in snapshot["repos"].items():
        md_lines.append(f"## {repo_key}")
        md_lines.append("")
        md_lines.append("| table | row_count | date_from | date_to |")
        md_lines.append("|---|---|---|---|")
        for table, stats in tables.items():
            md_lines.append(
                f"| {table} | {stats['row_count']} | {stats.get('date_from', 'n/a')} | "
                f"{stats.get('date_to', 'n/a')} |"
            )
        md_lines.append("")
    md_path = out_dir / f"dataset_summary_{timestamp}.md"
    md_path.write_text("\n".join(md_lines))

    print(f"Wrote {json_path}")
    print(f"Wrote {md_path}")


if __name__ == "__main__":
    main()
